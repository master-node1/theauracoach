function r(
  id: string,
  slots: MealSlot[],
  energyKcal: number,
  proteinG: number,
  fibreG: number,
  ingredients: [keyof typeof ING, number][],
  prepMinutes = 20,
  costTier: 1 | 2 | 3 = 1,
): PlanRecipe {
  return {
    id,
    name: id,
    slots,
    perServing: { energyKcal, proteinG, fibreG },
    ingredients: ingredients.map(([k, g]) => ({ ...ING[k]!, gramsPerServing: g })),
    prepMinutes,
    costTier,
  };
}

